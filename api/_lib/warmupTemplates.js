// Возвращает серию для ветки (или null, если прогрев не нужен - горячих ведёт команда).
function seriesFor(branch) {
  if (branch === 'warm') return WARM_SERIES;
  if (branch === 'cold') return COLD_SERIES;
  return null;
}

// Текст шага серии по индексу. name - имя клиента (может быть пустым).
function buildStepText(step, name) {
  if (!step || typeof step.text !== 'function') return '';
  const n = (name || '').trim();
  let out = step.text(n);
  // без имени не оставляем висячих запятых в начале строки
  if (!n) out = out.replace(/^,\s*/, '').replace(/\n,\s*/g, '\n');
  return out;
}

// Последний день серии (для понимания, когда прогрев закончен).
function lastDay(branch) {
  const s = seriesFor(branch);
  if (!s || !s.length) return 0;
  return s[s.length - 1].day;
}

