// ЕДИНАЯ ИСТОРИЯ ДИАЛОГА
// Системный промпт сюда НЕ пишется. Только разговор: user / assistant.
const MAX_HISTORY = 30;

/** Оставляет только реплики разговора, убирает любые system-остатки прошлых версий. */
function cleanHistory(history) {
  if (!Array.isArray(history)) return [];
  return history
    .filter((m) => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string')
    .filter((m) => m.content.trim().length > 0)
    .slice(-MAX_HISTORY);
}

/** Убирает один служебный блок {LEAD:...} с учётом вложенных скобок. */
function stripLeadBraces(text) {
  const src = String(text || '');
  let out = '';
  let i = 0;
  while (i < src.length) {
    const start = src.indexOf('{LEAD:', i);
    if (start === -1) { out += src.slice(i); break; }
    out += src.slice(i, start);
    // ищем закрывающую скобку с учётом вложенности
    let depth = 0;
    let j = start;
    let closed = false;
    for (; j < src.length; j++) {
      const ch = src[j];
      if (ch === '{') depth++;
      else if (ch === '}') {
        depth--;
        if (depth === 0) { closed = true; break; }
      }
    }
    if (!closed) break; // блок не закрыт - отбрасываем остаток
    i = j + 1;
  }
  return out;
}

/** Фильтрует уже отданную моделью реплику: служебные блоки заявки не должны уходить клиенту. */
function cleanReply(text) {
  return stripLeadBraces(
    String(text || '')
      // заявка в формате <<<LEAD>>>...<<<END>>> (единый формат для сайта и Telegram)
      .replace(/<<<LEAD>>>[\s\S]*?<<<END>>>/g, '')
      .replace(/<<<LEAD>>>[\s\S]*$/g, '')
  ).trim();
}

/** Собирает массив messages для модели: системный промпт отдельно + живая история + ход человека. */
function buildMessages(systemPrompt, history, userText) {
  const msgs = [{ role: 'system', content: String(systemPrompt || '') }];
  for (const m of cleanHistory(history)) msgs.push({ role: m.role, content: m.content });
  if (userText) msgs.push({ role: 'user', content: String(userText).slice(0, 3000) });
  return msgs;
}

/** Сжимает историю, если она разрослась: оставляет свежие реплики. */
function trimHistory(history) {
  return cleanHistory(history);
}

