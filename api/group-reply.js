function isFromBot(update) {
  const msg = update.message;
  return !!(msg && msg.from && msg.from.is_bot);
}

async function sendMessage(token, chatId, text) {
  await fetch(`https://api.telegram.org/bot${token}/sendMessage`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ chat_id: chatId, text }),
  });
}

module.exports = async function handler(req, res) {
  if (req.method !== 'POST') {
    res.status(200).json({ ok: true });
    return;
  }

  const token = process.env.SITE_BOT_TOKEN;
  const groupChatId = process.env.LEAD_TELEGRAM_CHAT_ID;
  const apiKey = process.env.DEEPSEEK_API_KEY;

  const update = req.body || {};
  const msg = update.message;

  res.status(200).json({ ok: true });

  if (!token || !groupChatId || !apiKey || !msg || !msg.text) return;
  if (isFromBot(update)) return;
  if (String(msg.chat && msg.chat.id) !== String(groupChatId)) return;
  if (msg.text.startsWith('/')) return;

  try {
    const upstream = await fetch('https://api.deepseek.com/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${apiKey}`,
      },
      body: JSON.stringify({
        model: 'deepseek-chat',
        messages: [
          { role: 'system', content: SYSTEM_PROMPT },
          { role: 'user', content: msg.text.slice(0, 2000) },
        ],
        temperature: 0.6,
        max_tokens: 500,
      }),
    });

    if (!upstream.ok) return;
    const data = await upstream.json();
    const reply = data?.choices?.[0]?.message?.content;
    if (reply) await sendMessage(token, groupChatId, reply);
  } catch (e) {
    console.error('group-reply failed', e);
  }
};
